#!/usr/bin/env python3
"""Write docs/internal-notes.md: commentary for internal preparation, kept out of the dashboard.

Same inputs as dashboard.py (data/*.csv via metrics.load), plus raw/_meta/teams.json and the raw
timeline of ddys-portal #693 for the dismissal event. Not linked from docs/dashboard.html.
"""
from __future__ import annotations

import csv
import json
from collections import Counter, defaultdict
from datetime import datetime

import dashboard as D
import metrics as M

OUT = D.ROOT / "docs" / "internal-notes.md"
FAST_MERGE_S = 60


def t(s: str) -> datetime:
    return datetime.strptime(s, "%Y-%m-%dT%H:%M:%SZ")


def pages(directory) -> list:
    items = []
    for f in sorted(directory.glob("p*.json")):
        if not f.name.endswith(".meta.json"):
            items += json.loads(f.read_bytes())
    return items


def pct(a, b):
    return f"{a} ({100 * a / b:.1f}%)"


def main():
    prs, findings, kept, rows, manifest, by_key, _ = D.build()
    rv = list(csv.DictReader(open(M.DATA / "reviews.csv", encoding="utf-8")))
    teams = json.loads((D.RAW / "_meta" / "teams.json").read_text())
    n = len(rows)
    lines = []
    w = lines.append
    table = M.table

    w("# Internal notes: peer review sample\n")
    w("Internal preparation notes. **Not linked from `docs/dashboard.html`.** "
      "Generated by `internal_notes.py` from the same data as the dashboard; re-run it rather than editing.\n")
    w(f"Population: the {n} measured PRs on the dashboard, unless a section says otherwise. "
      f"Window starts {D.fmt_utc(manifest['cutoff_utc'])}.\n")

    # 1. #692 / #693
    def review(num, pred):
        return next(v for v in rv if v["repo"] == "ddys-portal" and v["number"] == str(num) and pred(v))
    p692, p693 = by_key[("ddys-portal", 692)], by_key[("ddys-portal", 693)]
    cr692 = review(692, lambda v: v["original_state"] == "CHANGES_REQUESTED")
    ap692 = review(692, lambda v: v["state"] == "APPROVED")
    cr693 = review(693, lambda v: v["original_state"] == "CHANGES_REQUESTED")
    ap693 = review(693, lambda v: v["state"] == "APPROVED")
    dis = next(e for e in pages(D.RAW / manifest["org"] / "ddys-portal" / "pr" / "0693" / "timeline")
               if e["event"] == "review_dismissed")
    w("## 1. ddys-portal #692 / #693: change request overridden\n")
    w(f"The same change, opened twice: [#692]({p692['pr_url']}) into `test` and [#693]({p693['pr_url']}) "
      f"into `develop`. #692 is excluded from the dashboard as `{p692['excluded_reason']}`, so it does not "
      f"appear in the dashboard table. #693 does.\n")
    w(table(["Time (UTC)", "PR", "Event"], [
        [D.fmt_utc(cr692["submitted_at"]), "#692", f"{cr692['reviewer']} [requests changes]({cr692['review_url']})"],
        [D.fmt_utc(cr693["submitted_at"]), "#693", f"{cr693['reviewer']} [requests changes]({cr693['review_url']})"],
        [D.fmt_utc(ap692["submitted_at"]), "#692", f"{ap692['reviewer']} approves; the change request stays open"],
        [D.fmt_utc(p692["merged_at"]), "#692", f"{p692['merged_by']} merges, "
         f"{p692['seconds_between_approval_and_merge']} s after approving, with the change request still open"],
        [D.fmt_utc(ap693["submitted_at"]), "#693", f"{ap693['reviewer']} approves"],
        [D.fmt_utc(dis["created_at"]), "#693", f"{dis['actor']['login']} dismisses the change request: "
         f"“{dis['dismissed_review'].get('dismissal_message') or '(no message)'}”"],
        [D.fmt_utc(p693["merged_at"]), "#693", f"{p693['merged_by']} merges, "
         f"{int((t(p693['merged_at']) - t(dis['created_at'])).total_seconds())} s after the dismissal"],
    ], text_cols=3))
    w(f"\nThe approver, dismisser and merger on both PRs is the same account ({p693['merged_by']}). "
      f"It is the only merged PR in the sample with an open change request at merge (#692), and the only "
      f"manual dismissal of a review.\n")

    # 2. #636
    p636 = by_key[("ddys-portal", 636)]
    r636 = next(r for r in rows if r["repo"] == "ddys-portal" and r["number"] == 636)
    inl = [f for f in findings if f["repo"] == "ddys-portal" and f["counted_on"] == "636" and not f["excluded_reason"]]
    w("## 2. ddys-portal #636: 847 files, one inline comment\n")
    w(f"[#636]({p636['pr_url']}): {r636['size']:,} lines (+{int(p636['additions']):,} / "
      f"−{int(p636['deletions']):,}) across {int(p636['changed_files']):,} files. The largest measured PR.\n")
    w(f"- Author {p636['author']}; one approval, from {p636['approver']}, {r636['hours']:.1f} h after creation.")
    w(f"- {len(inl)} inline review comment" + (f" ({', '.join(f'[link]({f['url']})' for f in inl)})" if inl else "")
      + "; no change request.")
    w(f"- Merged by {p636['merged_by']} {int(p636['seconds_between_approval_and_merge']):,} s after the approval.\n")

    # 3. approve-and-merge within 60 s
    fast = sorted((r for r in rows if r["secs"] is not None and r["secs"] < FAST_MERGE_S), key=lambda r: -r["size"])
    same = sum(r["merged_by"] == r["approver"] for r in fast)
    w(f"## 3. {len(fast)} PRs merged within {FAST_MERGE_S} seconds of approval\n")
    w(f"- {pct(len(fast), n)} of measured PRs were merged less than {FAST_MERGE_S} s after the approval the "
      f"merge relied on.")
    w(f"- In {pct(same, len(fast))} of them, the approver merged.")
    bands = Counter("0–9 s" if r["secs"] < 10 else "10–29 s" if r["secs"] < 30 else "30–59 s" for r in fast)
    w(f"- Approval → merge: " + ", ".join(f"{k}: {bands[k]}" for k in ("0–9 s", "10–29 s", "30–59 s")) + ".")
    w("- By approver: " + ", ".join(f"{k} {v}" for k, v in Counter(r["approver"] for r in fast).most_common()) + ".")
    w("- By merger: " + ", ".join(f"{k} {v}" for k, v in Counter(r["merged_by"] for r in fast).most_common()) + ".")
    w(f"- Findings on these PRs: {sum(r['findings'] for r in fast)}; "
      f"{sum(r['comment_free'] for r in fast)} of the {len(fast)} approvals are comment-free.\n")
    w("All of them, largest first:\n")
    w(table(["Repo", "PR", "Lines", "Files", "Author", "Approver", "Merged by", "Approval → merge", "Findings"],
            [[r["repo"], f"[#{r['number']}]({r['url']})", f"{r['size']:,}", r["files"], r["author"], r["approver"],
              r["merged_by"], f"{r['secs']} s", r["findings"]] for r in fast], text_cols=2))
    w("")

    # 4. reviewer concentration
    w("## 4. Reviewer concentration\n")
    ap = Counter(r["approver"] for r in rows)
    mb = Counter(r["merged_by"] for r in rows)
    w(table(["Account", "Approvals", "Share of approvals", "Merges", "Share of merges"],
            [[a, ap[a], f"{100*ap[a]/n:.1f}%", mb[a], f"{100*mb[a]/n:.1f}%"]
             for a in sorted(set(ap) | set(mb), key=lambda a: -(ap[a] + mb[a]))]))
    w(f"\n- The approver also merged in {pct(sum(r['approver'] == r['merged_by'] for r in rows), n)} measured PRs.")
    w(f"- Two accounts performed every merge: " + ", ".join(f"{k} ({v})" for k, v in mb.most_common()) + ".\n")
    w("**Approvals by repo**\n")
    by_repo = defaultdict(Counter)
    for r in rows:
        by_repo[r["repo"]][r["approver"]] += 1
    repos = list(dict.fromkeys(r["repo"] for r in prs))
    w(table(["Repo", "Top approver", "Other approvers", "PRs", "Top approver's share"],
            [[repo, c.most_common(1)[0][0], ", ".join(f"{k} ({v})" for k, v in c.most_common()[1:]) or "—",
              sum(c.values()), f"{100*c.most_common(1)[0][1]/sum(c.values()):.1f}%"]
             for repo in repos if (c := by_repo.get(repo))], text_cols=3))
    w("")

    # 5. single-reviewer dependency
    top, top_n = ap.most_common(1)[0]
    others = [repo for repo in repos if by_repo.get(repo) and by_repo[repo].most_common(1)[0][0] == top]
    o_prs = sum(sum(by_repo[r].values()) for r in others)
    o_top = sum(by_repo[r][top] for r in others)
    members = teams["members"]
    member_of = sorted(s for s, ms in members.items() if any(m["login"] == top for m in ms))
    w("## 5. Single-reviewer dependency\n")
    w(f"- Every measured PR has exactly one approver.")
    w(f"- {top} approved {pct(top_n, n)} of all measured PRs and merged {pct(mb[top], n)}.")
    w(f"- In the {len(others)} repos where {top} is the top approver ({', '.join(others)}), "
      f"{top} approved {o_top} of {o_prs} PRs ({100*o_top/o_prs:.1f}%).")
    # Which team each measured PR asked for (first team review_requested event on the kept PR).
    requested = {}
    for r in rows:
        tl = pages(D.RAW / manifest["org"] / r["repo"] / "pr" / f"{r['number']:04d}" / "timeline")
        slug = next((e["requested_team"]["slug"] for e in tl
                     if e["event"] == "review_requested" and e.get("requested_team")), None)
        requested[(r["repo"], r["number"])] = slug
    for slug in sorted({s for s in requested.values() if s}):
        ms = [m["login"] for m in members.get(slug, [])]
        asked = [r for r in rows if requested[(r["repo"], r["number"])] == slug]
        approved = Counter(r["approver"] for r in asked)
        repos_asked = sorted({r["repo"] for r in asked}, key=repos.index)
        outside = sum(v for k, v in approved.items() if k not in ms)
        w(f"- `{slug}` was requested on {len(asked)} measured PRs ({', '.join(repos_asked)}). It has {len(ms)} "
          f"members; approvals on those PRs: " + ", ".join(f"{m} {approved[m]}" for m in ms)
          + (f"; non-members {outside}" if outside else "") + ".")
    none = sum(1 for v in requested.values() if not v)
    if none:
        w(f"- {none} measured PRs have no team review request.")
    w(f"- {top} is a member of: {', '.join(f'`{s}`' for s in member_of)}.")
    w(f"- Team membership is as fetched on {teams['fetched_at_range'][0][:10]}, not historical.\n")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(D.ROOT)}: {len(fast)} fast merges listed")


if __name__ == "__main__":
    main()
